// 自分の優先度を上げる。import するだけで効く。
//
//   import './prio.mjs'
//
// ★なぜ要るか（2026-11-11）
//   予定タスクから起動されたものは **BelowNormal** で動く。
//   Task Scheduler の既定の優先度は 7（BELOW_NORMAL）で、bash も node もそれを
//   引き継ぐ。競艇のタスクは17本すべて `<Priority>` を一度も指定していなかった。
//
//   この機械は搭載7.8GB。11/11 の実測で **ページング 47,000回/秒・空き0.5GB**、
//   常駐16本の実メモリ合計がわずか139MBまで追い出されていた。
//   その状態で BelowNormal の処理は、ほとんど進まない。実際に：
//     ・11/08 ログが 01:04〜11:11 の **607分** 途切れた
//     ・11/11 ログが 01:42〜09:23 の **461分** 途切れた
//     ・11/11 の作り直しが **6時間15分** 走って時間切れになった
//   機械はどちらも起動したままで、スリープもしていない。CPUとメモリの
//   奪い合いに負けていただけ。
//
// ★なぜ各スクリプトに入れるのか（親で上げるだけでは効かない）
//   実測：node の親で setPriority(-7) しても、execFileSync で呼んだ子は 0 のまま。
//   bash 経由も同じく引き継がれない。**優先度は継承されない**。
//   だから「重いことをする本人」が自分で上げるしかない。
//
// ⚠ High にはしないこと。OSの応答を奪ってかえって不安定になる。
//   -7 は Windows で ABOVE_NORMAL。
import { setPriority } from 'node:os'

try { setPriority(-7) } catch { /* 上げられなくても処理は続ける */ }
